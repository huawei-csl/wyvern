def extract_level_headings(text: str, level: int = 2):
    heading_pattern = r"^(#{%d})\s(.+?)\n" % (level)
    headings = re.findall(heading_pattern, text, flags=re.MULTILINE)
    return [f"{level * '#'} {heading.strip()}" for _, heading in headings]

def convert_citations_to_superscript(text: str) -> str:
    """Detect the citations in the given text, with the format [integer, text].
    Convert them to small superscript, and remove the comma between multiple 
    consecutive citations.
    
    Parameters
    ----------
    - text [`str`]: input text
    
    Output
    ------
    - `str`: converted text
    """
    # This pattern matches the citations of the form [integer, text]
    citation_pattern = r'\[(\d+),\s*([^\]]+)\]'
    
    # This function will wrap the citation in superscript tags
    def superscript_match(match):
        citation_number = match.group(1)
        citation_text = match.group(2)
        return f'<sup><small>[{citation_number}, {citation_text}]</small></sup>'
    
    text_with_superscripts = re.sub(citation_pattern, superscript_match, text)
    
    # Remove the commas between multiple consecutive citations
    result_text = re.sub(r'</sup>,\s?<sup>', '</sup> <sup>', text_with_superscripts)
    
    return result_text


def remove_urls(text):
    # Match [[integer, text](url)]
    pattern = r'\[\[(\d+),([^\]]+)\]\([^\)]+\)\]'
    
    # Replace with [integer, text]
    def replacer(match):
        return f"[{match.group(1)}, {match.group(2).strip()}]"
    
    return re.sub(pattern, replacer, text)


def format_citations_to_superscript(text):
    # Match [[integer, text with spaces](url)]
    text = text.replace("<small><sup>", "").replace("</small></sup>","").replace("<sup><small>", "").replace("</sup></small>","")
    pattern = r'\[\[(\d+),([^\]]+)\]\([^\)]+\)\]'
    
    def replacer(match):
        citation = match.group(0)  # The full match, e.g., [[123, text](url)]
        return f"<small><sup>{citation}</sup></small>"
    
    text = re.sub(pattern, replacer, text)
    text = re.sub(r'</sup>,\s?<sup>', '</sup> <sup>', text)
    text = re.sub(r'</small>,\s?<small>', '</small> <small>', text)
    return text

def fix_citations(text: str, 
                  df: pd.DataFrame):
    # Match any citation like [1], [1, 2], [1, 2, 3], and so on
    pattern = re.compile(r'\[(\d+(?:\s*,\s*\d+)*)\]')

    def replacer(match):
        # Get the string inside the brackets, without the latters
        citation_ids = match.group(1)
        ids = [int(cid.strip()) for cid in citation_ids.split(',')]
        
        replaced = ''
        for cid in ids:
            try:
                citation_text = f", {df.at[cid - 1, 'identifier']}"
            except KeyError:
                citation_text = ''
            replaced += f'[{cid}{citation_text}]'
        
        return replaced

    return pattern.sub(replacer, text)

def find_section_of_text_unit(text_unit: str, 
                              report: str) -> str:
    """Given a text unit, it returns the (first) section where it appears.
    
    Parameters
    ----------
    - text_unit [`str`]: text snippet
    - report [`str`]: report

    Output
    ------
    - `str`: the updated version of the text unit or `None` if it was not found
    """
    sections = extract_markdown_sections(report, False)

    for sec in sections:
        if text_unit in sec[1]:
            return sec[1]
        
    if contains_markdown_table(text_unit):
        return find_section_of_text_unit(text_unit.strip().split("\n")[0], report)
    return None


def generate_subtables(table: str):
    """Given a string that represents a table in markdown format, generate the
    subtables, each containing the header and one of the row of the table.
    
    Parameters
    ----------
    - table [`str`]: the table in markdown format
    
    Output
    - `list[str]`: list of subtables in markdown format
    """
    table_lines = table.strip().split("\n")

    # Usually the first contains headings, and the second the divider: use
    # this as default setting
    divider_index = 2
    for i, line in enumerate(table_lines):
        if line.upper().isupper() == False:
            divider_index = i + 1

    table_header = "\n".join(table_lines[:divider_index])

    subtables = []
    for line in table_lines[divider_index:]:
        subtables.append("\n".join([table_header, line]))
    return subtables


def contains_markdown_table(text_unit: str) -> bool:
    lines = text_unit.strip().splitlines()
    for i in range(len(lines) - 1):
        header = lines[i].strip()
        separator = lines[i + 1].strip()
        
        # Check if both header and separator use pipe characters
        if '|' in header and '|' in separator:
            # Check for the separator line pattern: at least three dashes between pipes
            if re.fullmatch(r'\s*\|?( *:?-+:? *\|)+ *:?-+:? *\|?\s*', separator):
                return True
    return False

class TextSimilarityEvaluator():
    def __init__(self):
        pass

    def sequence_matcher(self, text1: str, text2: str):
        similarity = difflib.SequenceMatcher(None, text1, text2).ratio()
        return similarity
    
    def jaccard_similarity(self, text1: str, text2: str):
        words1 = set(text1.lower().split())
        words2 = set(text2.lower().split())
        intersection = words1.intersection(words2)
        union = words1.union(words2)
        similarity = len(intersection) / len(union)
        return similarity
    
    def tfidf_similarity(self, text1: str, text2: str):
        vectorizer = TfidfVectorizer()
        tfidf = vectorizer.fit_transform([text1, text2])
        similarity = cosine_similarity(tfidf[0:1], tfidf[1:2])[0][0]
        return similarity
    
    def embedding_similarity(self, 
                             text1: str, 
                             text2: str, 
                             model_id: str = "allenai-specter"):
        # Load the embedding model
        model = SentenceTransformer(model_id)
        # Compute the embeddings
        emb1 = model.encode(text1, convert_to_tensor=True)
        emb2 = model.encode(text2, convert_to_tensor=True)
        similarity = SentenceTransformer.util.pytorch_cos_sim(emb1, emb2).item()
        return similarity
    
    def levenshtein_distance(self,
                             text1: str,
                             text2: str,
                             convert_to_sim: bool = True):
        distance = Levenshtein.distance(text1, text2) / max(len(text1), len(text2))
        if convert_to_sim: 
            return 1 - distance
        else:
            return distance        


class MarkdownTableHandler:
    def __init__(self):
        pass

    def hide_tables(self, text):
        table_regex = re.compile(
            r'(?:\|.*\|\s*\n)+\|(?:\s*:?-+:?\s*\|)+\s*\n(?:\|.*\|\s*\n?)+',
            re.MULTILINE
        )
        return table_regex.sub('', text).strip()

    def extract_markdown_tables(self, text):
        table_regex = re.compile(
            r'(?:\|.*\|\s*\n)+\|(?:\s*:?-+:?\s*\|)+\s*\n(?:\|.*\|\s*\n?)+',
            re.MULTILINE
        )
        
        tables = table_regex.findall(text)
        return [table.strip() for table in tables]

def remove_surrounding_quotes(s):
    for quote in ('"', "'"):
        count = 0
        while s.startswith(quote * (count + 1)) and s.endswith(quote * (count + 1)):
            count += 1
        if count > 0:
            return s[count:-count]
    return s
