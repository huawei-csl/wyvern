AI_GENERATED_DISCLAIMER = (
    "> **AI-generated content:** this report was generated by AI and may "
    "contain errors. Please verify important information.\n\n"
)


def remove_ai_generated_disclaimer(report: str) -> str:
    """Remove the disclaimer about AI-generated content from the beginning 
    of a report.
    """
    return report.removeprefix(AI_GENERATED_DISCLAIMER)


def write_generated_report(markdown_path: str, report: str) -> None:
    """Write a report with the AI-generated content disclaimer at the top.
    """
    if not report.startswith(AI_GENERATED_DISCLAIMER):
        report = AI_GENERATED_DISCLAIMER + report.lstrip("\n")

    with open(markdown_path, "w", encoding="utf-8") as report_file:
        report_file.write(report)


def parse_llm_json(response: str, 
                   max_chars: int = 100_000, 
                   max_depth: int = 20):
    """Extract and safely parse a size- and depth-limited JSON value."""
    if len(response) > max_chars:
        raise ValueError("LLM JSON response exceeds the size limit")

    start = next((i for i, char in enumerate(response) if char in "[{"), None)
    if start is None:
        raise ValueError("LLM response does not contain JSON")

    stack = []
    in_string = False
    escaped = False
    pairs = {"}": "{", "]": "["}
    for i in range(start, len(response)):
        char = response[i]
        if in_string:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                in_string = False
            continue
        if char == '"':
            in_string = True
        elif char in "[{":
            stack.append(char)
            if len(stack) > max_depth:
                raise ValueError("LLM JSON response exceeds the nesting limit")
        elif char in "]}":
            if not stack or stack.pop() != pairs[char]:
                raise ValueError("LLM response contains malformed JSON")
            if not stack:
                return json.loads(response[start:i + 1])

    raise ValueError("LLM response contains incomplete JSON")


def convert_markdown_to_html(
    markdown_path: str,
    html_path: str,
    *,
    css_path: str = "style/style.css",
    page_title: Optional[str] = None,
    embed_resources: bool = False,
    self_contained: bool = False,
    ) -> None:
    """Convert a Markdown file to HTML with Pandoc.
    """
    command = [
        "pandoc",
        "--css=" + os.path.abspath(css_path),
        "-s",
        "-o",
        html_path,
        markdown_path,
        "--mathml",
    ]
    if embed_resources:
        command.append("--embed-resources")
    if self_contained:
        command.append("--self-contained")
    if page_title is not None:
        command.extend(["--variable", f"pagetitle={page_title}"])

    subprocess.run(command, check=True)


def normalize_arxiv_url(url: str) -> str:
    """Normalize arXiv article URLs to their canonical PDF URL.
    """
    try:
        url = url.strip()
        parsed = urllib.parse.urlsplit(url)
        netloc = parsed.netloc.replace("www.", "")
        if netloc != "arxiv.org":
            return url

        match = re.match(
            r"^/(?:abs|pdf|html)/([0-9]+\.[0-9]+(?:\.[0-9]+)?)(v\d+)?(?:\.pdf)?/?$",
            parsed.path,
        )
        if not match:
            return urllib.parse.urlunsplit((parsed.scheme or "https", parsed.netloc, parsed.path, "", ""))

        paper_id, version = match.groups()
        return f"https://arxiv.org/pdf/{paper_id}{version or ''}"
    except Exception as e:
        logger.warning(e)
        return url

def remove_citations(text):
    # Remove citations in the form of [3], [8], [4] and [3] or similar
    text = re.sub(r"\[\d+(?:,\d+)*\]", "", text)  # Handles citations like [3],[8],[4]
    # Remove commas if they are followed directly by a space or a period after citation removal
    text = re.sub(r"\s*,\s*(?=\s*\.)", "", text)  # Remove the comma before a period
    text = re.sub(r" \[\d+", "", text)  # Remove citations with a space before them
    text = text.replace(" |", "").replace("]", "")  # Removes the pipe and extra closing brackets if present
    return text


def modify_latex_equations(text: str) -> str:
    """Given an input text, modify the LaTeX equations to make them 
    Markdown-friendly.
    
    Parameters
    ----------
    - text [`str`]: input text
    
    Output
    ------
    - `str`: text with modified equations
    """
    # 1) Convert block formulas \[...\] to $$ ... $$
    text = re.sub(r'\\\[(.*?)\\\]', 
                  lambda m: f'$$ {m.group(1).strip()} $$', 
                  text, 
                  flags=re.DOTALL)
    # 2) Convert inline formulas \(...\) to $...$ (no inner spaces next to $)
    text = re.sub(r'\\\((.*?)\\\)', 
                  lambda m: f'${m.group(1).strip()}$', 
                  text, 
                  flags=re.DOTALL)
    return text


@lru_cache(maxsize=None)
def _get_tokenizer(model_id: str):
    """Load each model tokenizer once and reuse it across token counts."""
    return AutoTokenizer.from_pretrained(model_id)


def get_number_tokens(text: str, model_id: str) -> int:
    """Get the number of tokens of a text for a given model.
    """
    try:
        tokenizer = _get_tokenizer(model_id)
        num_tokens = len(tokenizer(text)['input_ids'])
    except Exception as e:
        logger.warning(
            f"The tokenizer of the model {model_id} was not found in HF: '{e}'."
            "Using a proxy computation of the number of tokens."
        )        
        return len(text) // 6
    return num_tokens


def get_number_words(text: str) -> int:
    """Get the number of words of a given text.
    """
    count = len(re.findall(r'\w+', text))
    return count
    

def extract_markdown_sections(text, exclude_references=False):
    heading_pattern = r'^(#{1,6})\s+(.*)'

    sections = []
    current_section = None
    current_text = []

    for line in text.splitlines():
        match = re.match(heading_pattern, line)
        if match:
            if current_section is not None:
                sections.append((current_section, '\n'.join(current_text).strip() if current_text else ''))

            level = len(match.group(1))  # Number of # indicates the heading level
            section_title = match.group(2).strip()

            current_section = f"{'#' * level} {section_title}"
            current_text = []
        else:
            current_text.append(line.strip())

    if current_section is not None:
        sections.append((current_section, '\n'.join(current_text).strip() if current_text else ''))
    if exclude_references:
        sections = sections[:-1]
    return sections

