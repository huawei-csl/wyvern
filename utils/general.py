def find_last_report_version(folder_path: str, stem: Optional[str]=None) -> int:
    """Check the files in the provided folder for labeled filenames containing
    the string '_v*'. Return the maximum number (corresponding to the latest
    version, or -1 in case of no match).
    
    Parameters
    ----------
    - folder_path [`str`]: path of the folder
    
    Output
    ------
    - `int`: the maximum version id
    """
    files = os.listdir(folder_path)
    
    pattern = r'_v(\d+)'
    version_numbers = []
    
    for filename in files:
        if (stem != None) and (stem not in filename):
            continue
        match = re.search(pattern, filename)
        if match:
            version_numbers.append(int(match.group(1)))
    
    return max(version_numbers, default=-1)


def filter_arxiv_url(urls: Iterable[str]) -> list[str]:
    """Given a list of URLs (not necessarily pointing to arxiv), if there are
    multiple versions of the same paper, keep only the most recent one. I.e., 
    if there is an URL without the version identifier consider that one as the
    most recent, otherwise keep the URL with the highest version identifier
    number.
    
    Parameters
    ----------
    - urls [`Iterable[str]`]: list of URLs to process

    Output
    ------
    - [`list`]: list of filtered urls
    """

    # Regex pattern to match URLs of arxiv paper and extract their
    # base identifier and version number
    arxiv_pattern = r"https://arxiv.org/(?:abs|pdf|html)/([0-9]+\.[0-9]+(?:\.[0-9]+)?)(v(\d+))?"
    
    urls = [normalize_arxiv_url(url) for url in urls]

    # defaultdict returns an empty list whenever accessing a non-existing key
    paper_groups = defaultdict(list)
    non_arxiv_urls = []
    
    for url in urls:
        match = re.fullmatch(arxiv_pattern, url)
        if match:
            base_paper_id = match.group(1)
            version_str = match.group(3)
            version = int(version_str) if version_str else None
            paper_groups[base_paper_id].append((url, version))
        else:
            non_arxiv_urls.append(url)
    
    result = []
    for base_paper_id, group in paper_groups.items():
        no_version_url = next(
            (url for url, version in group if version is None), 
            None
            )
        
        # If there is a version of the URL without the version identifier keep
        # that one, otherwise select the one with the maximum version number
        if no_version_url:
            result.append(no_version_url)
        else:
            latest_version_url = max(group, key=lambda x: x[1])[0]
            result.append(latest_version_url)
    
    result.extend(non_arxiv_urls)    

    for url in urls:
        if url not in result:
            logger.info((
                f"Removing URL {url} because it is not the latest version in "
                f"{str([t[0] for t in paper_groups[re.fullmatch(arxiv_pattern, url).group(1)]])}"
                ))
    return result

